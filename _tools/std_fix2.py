# <b>[코드]</b> 뒤부터 <br> 또는 </div> 앞까지가 그 성취기준의 문장이다.
PAT = re.compile(r'(<b>\[((?:12지구|10통과1)\d\d-\d\d)\]</b>\s*)([^<]*)')

changed_files = []
for f in sorted(glob.glob(ROOT + "earth-science-2/*/index.html") + glob.glob(ROOT + "integrated-science-1/*/index.html")):
    s = open(f, encoding="utf-8", newline="").read()
    n = [0]
    def rep(m):
        want = STD.get(m.group(2))
        if not want or m.group(3).strip() == want:
            return m.group(0)
        n[0] += 1
        return m.group(1) + want
    s2 = PAT.sub(rep, s)
    if n[0]:
        open(f, "w", encoding="utf-8", newline="").write(s2)
        changed_files.append((os.path.relpath(f, ROOT).replace("\\", "/"), n[0]))

for f, n in changed_files:
    print("고침", f, n, "곳")
if not changed_files:
    print("바꿀 것 없음")

s = open(P, encoding="utf-8", newline="").read()
n = 0
for url, story in S.items():
    cnt = len(story.split("), ")) if "(" in story else 0
    word = {2: "두", 3: "세", 4: "네"}.get(cnt, str(cnt))
    add = " 이야기 " + word + " 편 — " + story + "."
    # 그 단원의 한 줄을 찾아 desc 끝에 덧붙인다
    pat = re.compile(r'(\{"subject".*?"url": "' + re.escape(url) + r'"\})')
    m = pat.search(s)
    if not m:
        print("  !! 줄 못 찾음:", url); continue
    row = json.loads(m.group(1))
    if "이야기" in row["desc"]:
        continue
    row["desc"] = row["desc"].rstrip() + add
    s = s[:m.start(1)] + json.dumps(row, ensure_ascii=False) + s[m.end(1):]
    n += 1
open(P, "w", encoding="utf-8", newline="").write(s)
